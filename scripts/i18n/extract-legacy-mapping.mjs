/**
 * Recovers the `old i18n key -> new i18n key` mapping from the abandoned
 * `chore/locales-refactor` branch, so its decisions can be replayed on top of
 * `integration/v2.5-develop` without merging that branch.
 *
 *   npm run i18n:extract-mapping
 *
 * How it works: the rename commits on that branch rewrote call sites in place, so
 * inside every diff hunk a run of removed lines lines up 1:1 with a run of added
 * lines. Aligning those runs and pulling the i18n key out of each pair recovers
 * the author's intended mapping exactly -- no value guessing, no heuristics.
 *
 * Output: scripts/i18n/legacy-key-mapping.json
 *
 * The branch is only read, never merged. Two commits on it are deliberately NOT
 * listed below: d015537e pins SDK 3.1.4-beta and 0fa5c11b is an unrelated sepolia
 * fix. Neither has anything to do with i18n and both would be a regression here.
 */
import { execFileSync } from "node:child_process"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, "..", "..")
const outFile = path.join(__dirname, "legacy-key-mapping.json")

const RENAME_COMMITS = [
  "51fc1757", // chore(i18n): rename t() and Trans keys to new conventions
  "127235dc", // chore(i18n): replace hardcoded user-visible strings with t()
  "b6904dbc", // chore(i18n): fix typo errors
]
const MERGE_BASE = "265eecaa" // chore(format): consistent formatting of numbers
const LOCALES_TIP = "6d59dfc9" // Merge branch 'main' into chore/locales-refactor

const KEY_RE = /(?:\bt\(|i18nKey=)["']([A-Za-z0-9_.\-]+)["']/g

function git(args) {
  return execFileSync("git", args, {
    cwd: rootDir,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  })
}

function assertReachable() {
  const missing = []
  for (const ref of [...RENAME_COMMITS, MERGE_BASE, LOCALES_TIP]) {
    try {
      git(["cat-file", "-e", `${ref}^{commit}`])
    } catch {
      missing.push(ref)
    }
  }
  if (missing.length) {
    console.error(
      `Cannot reach these commits: ${missing.join(", ")}\n` +
        "They live on chore/locales-refactor. Run:\n" +
        "  git fetch origin chore/locales-refactor\n" +
        "If the branch is gone for good, the committed legacy-key-mapping.json is\n" +
        "the artifact of record and this script need not run again.",
    )
    process.exit(1)
  }
}

const keysIn = (line) => [...line.matchAll(KEY_RE)].map((m) => m[1])

/** Align equal-length runs of removed/added lines and pull out the key pairs. */
function harvest(diff, mapping, conflicts) {
  let minus = []
  let plus = []

  const flush = () => {
    if (minus.length && minus.length === plus.length) {
      for (let i = 0; i < minus.length; i += 1) {
        const from = keysIn(minus[i])
        const to = keysIn(plus[i])
        if (from.length !== to.length) continue
        for (let j = 0; j < from.length; j += 1) {
          if (from[j] === to[j]) continue
          const prev = mapping.get(from[j])
          if (prev !== undefined && prev !== to[j]) {
            if (!conflicts.has(from[j])) conflicts.set(from[j], new Set([prev]))
            conflicts.get(from[j]).add(to[j])
          }
          mapping.set(from[j], to[j])
        }
      }
    }
    minus = []
    plus = []
  }

  for (const line of diff.split("\n")) {
    if (line.startsWith("@@") || line.startsWith("diff ") || line.startsWith("index ")) {
      flush()
    } else if (line.startsWith("---") || line.startsWith("+++")) {
      // file headers, not content
    } else if (line.startsWith("-")) {
      if (plus.length) flush()
      minus.push(line.slice(1))
    } else if (line.startsWith("+")) {
      plus.push(line.slice(1))
    } else {
      flush()
    }
  }
  flush()
}

assertReachable()

const mapping = new Map()
const conflicts = new Map()
for (const commit of RENAME_COMMITS) {
  harvest(git(["show", "--unified=0", "--format=", commit]), mapping, conflicts)
}

const payload = {
  $comment:
    "GENERATED by scripts/i18n/extract-legacy-mapping.mjs from chore/locales-refactor. " +
    "`confident` came from diff-aligned call-site rewrites and is authoritative -- the " +
    "branch author renamed these by hand. Do NOT re-run after review: it overwrites " +
    "any corrections recorded in `corrections`/`rejected`.",
  source: {
    mergeBase: MERGE_BASE,
    localesRefactorTip: LOCALES_TIP,
    renameCommits: RENAME_COMMITS,
    excludedCommits: {
      d015537e: "pins SDK 3.1.4-beta, unrelated and a regression",
      "0fa5c11b": "sepolia periodic hooks fix, unrelated",
    },
  },
  stats: { confident: mapping.size, conflicting: conflicts.size },
  confident: Object.fromEntries(
    [...mapping.entries()].sort(([a], [b]) => a.localeCompare(b)),
  ),
  conflicting: Object.fromEntries(
    [...conflicts.entries()]
      .map(([k, v]) => [k, [...v].sort()])
      .sort(([a], [b]) => a.localeCompare(b)),
  ),
}

fs.writeFileSync(outFile, `${JSON.stringify(payload, null, 2)}\n`)
console.log(`wrote ${path.relative(rootDir, outFile)}`)
console.log(`  confident mappings (from call-site diffs): ${payload.stats.confident}`)
console.log(`  conflicting targets (need review)        : ${payload.stats.conflicting}`)
