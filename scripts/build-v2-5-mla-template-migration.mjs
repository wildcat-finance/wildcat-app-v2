import { createHash } from "crypto"
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "fs"
import { dirname, resolve } from "path"
import { fileURLToPath } from "url"

const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const repositoryRoot = resolve(scriptDirectory, "..")
const templatePath = resolve(
  repositoryRoot,
  "src/app/api/mla/default-mla.json",
)
const migrationPath = resolve(
  repositoryRoot,
  "prisma/migrations/20260728000000_v2_5_default_mla_templates/migration.sql",
)

const supportedChainIds = [1, 11155111, 9745, 9746]

const borrowerFields = [
  ["network.chainId", "Insert Network Chain ID"],
  ["network.name", "Insert Network Name"],
  ["asset.name", "Insert Asset Name"],
  ["asset.symbol", "Insert Asset Symbol"],
  ["market.marketType", "Insert Market Type"],
  ["market.name", "Insert Market Name"],
  ["market.symbol", "Insert Market Symbol"],
  ["borrower.name", "Insert Borrower Name"],
  ["borrower.jurisdiction", "Insert Jurisdiction"],
  ["borrower.physicalAddress", "Insert Physical Address"],
  ["borrower.entityKind", "Insert Entity Kind"],
  ["market.depositAccess", "Insert Deposit Access"],
  ["market.transferAccess", "Insert Transfer Access"],
  ["market.withdrawalAccess", "Insert Withdrawal Access"],
  ["asset.address", "Insert Asset Address"],
  ["market.address", "Insert Market Address"],
  ["borrower.address", "Insert Borrower Address"],
  ["chainalysisOracle.address", "Insert Chainalysis Oracle Address"],
  ["hooksFactory.address", "Insert Hooks Factory Address"],
  ["market.capacity", "Insert Market Capacity"],
  ["market.minimumDeposit", "Insert Minimum Deposit"],
  ["market.delinquencyGracePeriod", "Insert Delinquency Grace Period"],
  ["market.withdrawalBatchDuration", "Insert Withdrawal Batch Duration"],
  ["market.fixedTermEndTime", "Insert Fixed Term End Time"],
  ["market.firstWithdrawalWindowStart", "Insert First Withdrawal Window Start"],
  ["market.periodDuration", "Insert Withdrawal Period Duration"],
  ["market.withdrawalWindowDuration", "Insert Withdrawal Window Duration"],
  ["market.nextWithdrawalWindowStart", "Insert Next Withdrawal Window Start"],
  ["borrower.timeSigned", "Insert Borrower Time Signed"],
  ["sla.timeUpdated", "Insert SLA Time Updated"],
  ["market.apr", "Insert APR"],
  ["market.aprLabel", "Insert APR"],
  ["market.delinquencyFee", "Insert Delinquency Fee"],
  ["market.reserveRatio", "Insert Reserve Ratio"],
  ["market.allowClosureBeforeTerm", "Insert Allow Closure Before Term"],
  ["market.allowTermReduction", "Insert Allow Term Reduction"],
].map(([source, placeholder]) => ({ source, placeholder }))

const lenderFields = [
  ["lender.timeSigned", "Insert Lender Time Signed"],
  ["lender.timeSignedDayOrdinal", "Insert Lender Time Signed Day Ordinal"],
  ["lender.timeSignedMonthYear", "Insert Lender Time Signed Month Year"],
  ["lender.address", "Insert Lender Address"],
].map(([source, placeholder]) => ({ source, placeholder }))

const template = JSON.parse(readFileSync(templatePath, "utf8"))
const templateText = `${template.plaintext}\n${template.html}`
const referencedFields = new Set(
  [...templateText.matchAll(/\{\{([^}]+)\}\}/g)].map((match) => match[1]),
)
const configuredFields = new Set(
  [...borrowerFields, ...lenderFields].map(({ source }) => source),
)
const unconfiguredFields = [...referencedFields].filter(
  (field) => !configuredFields.has(field),
)
if (unconfiguredFields.length > 0) {
  throw new Error(
    `Template references unconfigured fields: ${unconfiguredFields.join(", ")}`,
  )
}
if (/force[\s-]*buy\s*back|force[\s-]*buyback/i.test(templateText)) {
  throw new Error("The V2.5 MLA template still contains force-buyback language")
}
for (const requiredField of [
  "market.firstWithdrawalWindowStart",
  "market.periodDuration",
  "market.withdrawalWindowDuration",
  "market.nextWithdrawalWindowStart",
]) {
  if (!referencedFields.has(requiredField)) {
    throw new Error(`V2.5 MLA template is missing ${requiredField}`)
  }
}

const dollarQuote = (tag, value) => {
  const delimiter = `$${tag}$`
  if (value.includes(delimiter)) {
    throw new Error(`Template contains reserved SQL delimiter ${delimiter}`)
  }
  return `${delimiter}${value}${delimiter}`
}
const sqlString = (value) => `'${value.replaceAll("'", "''")}'`
const sourceSha256 = createHash("sha256")
  .update(readFileSync(templatePath))
  .digest("hex")

const migration = `/*
  Generated by scripts/build-v2-5-mla-template-migration.mjs.
  Source: src/app/api/mla/default-mla.json
  Source SHA-256: ${sourceSha256}

  Preserve every historical template and rendered MLA. Existing defaults are
  hidden and demoted; one V2.5 default is inserted for each supported chain.
*/

BEGIN;

UPDATE "MlaTemplate"
SET "isDefault" = false,
    "hide" = true
WHERE "chainId" IN (${supportedChainIds.join(", ")})
  AND "isDefault" = true;

INSERT INTO "MlaTemplate" (
  "chainId",
  "name",
  "description",
  "hide",
  "isDefault",
  "html",
  "plaintext",
  "borrowerFields",
  "lenderFields"
)
SELECT
  supported."chainId",
  ${sqlString(template.name)},
  'Protocol V2.5 default MLA template.',
  false,
  true,
  ${dollarQuote("wildcat_v25_html", template.html)},
  ${dollarQuote("wildcat_v25_plaintext", template.plaintext)},
  ${sqlString(JSON.stringify(borrowerFields))}::jsonb,
  ${sqlString(JSON.stringify(lenderFields))}::jsonb
FROM (
  VALUES ${supportedChainIds.map((chainId) => `(${chainId})`).join(", ")}
) AS supported("chainId");

DO $$
BEGIN
  IF (
    SELECT COUNT(*)
    FROM "MlaTemplate"
    WHERE "chainId" IN (${supportedChainIds.join(", ")})
      AND "isDefault" = true
      AND "hide" = false
      AND "name" = ${sqlString(template.name)}
  ) <> ${supportedChainIds.length} THEN
    RAISE EXCEPTION 'V2.5 default MLA template backfill incomplete';
  END IF;
END $$;

COMMIT;
`

if (process.argv.includes("--write")) {
  mkdirSync(dirname(migrationPath), { recursive: true })
  writeFileSync(migrationPath, migration)
} else {
  if (!existsSync(migrationPath)) {
    throw new Error(
      "Generated migration is missing; rerun this script once with --write",
    )
  }
  if (readFileSync(migrationPath, "utf8") !== migration) {
    throw new Error(
      "Generated migration differs from its source; do not rewrite a deployed migration",
    )
  }
}
